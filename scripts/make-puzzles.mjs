// Builds worker/puzzles.js: one graded poker decision per day, the same for everyone.
// Each spot is a heads-up single-raised pot, 100 BB deep, where you face a bet on the flop, turn or river.
// Fold, call and raise are graded ahead of time by the same analysis that grades Ranked (rating.js), at many
// more samples than a live table can afford, and a spot is kept only when one answer is clearly right.
// Run: node scripts/make-puzzles.mjs [days]   (deterministic: the same input always builds the same file)
import {writeFileSync} from 'node:fs';
import '../worker/grading.js';
const R=globalThis.RivlRating,strength=globalThis.preflopStrength;
export const START='2026-10-20';
const DAYS=Number(process.argv[2])||366,ITERS=12000,BB=100,STACK=100*BB;
const RANKS='23456789TJQKA',SUITS='♠♥♦♣';
const DECK=[...RANKS].flatMap(r=>[...SUITS].map(s=>r+s));
const GOOD=new Set(['Brilliant','Best','Excellent']),CLEAR=new Set(['Inaccuracy','Mistake','Blunder']);
const STREET_NAMES=['Flop','Turn','River'];
const SIZES=[1/3,1/2,2/3,3/4,1,1.5];
const round=x=>Math.max(BB/2,Math.round(x/(BB/2))*(BB/2));
const cap=t=>t[0].toUpperCase()+t.slice(1);
const bb=x=>`${+(x/BB).toFixed(1)} BB`;

function spot(rand){
  const pick=a=>a[Math.floor(rand()*a.length)];
  const deck=DECK.slice();for(let i=deck.length-1;i>0;i--){const j=Math.floor(rand()*(i+1));[deck[i],deck[j]]=[deck[j],deck[i]]}
  const hero=[deck.pop(),deck.pop()];
  // You opened from the button or cutoff and the big blind called, or you defended the big blind against an open.
  const ip=rand()<.55,seat=pick(['the button','the cutoff']);
  if(strength(hero)<(ip?.42:.36))return null;
  const vName=ip?'the big blind':seat;
  const street=rand()<.25?0:rand()<.45?1:2; // index into STREET_NAMES
  const board=deck.splice(0,3+street);
  let pot=BB/2+2*2.5*BB,stack=STACK-2.5*BB;
  const story=[ip?`You open to 2.5 BB on ${seat}. The big blind calls.`:`${cap(seat)} opens to 2.5 BB. You call in the big blind.`];
  for(let s=0;s<street;s++){
    const cards=board.slice(0,3+s).slice(s?2+s:0).join(' ');
    if(rand()<.35){story.push(`${STREET_NAMES[s]} ${cards}: checked through.`);continue}
    const b=round(pot*pick([1/3,1/2,2/3,3/4]));
    story.push(ip?`${STREET_NAMES[s]} ${cards}: the big blind checks, you bet ${bb(b)}, they call.`:`${STREET_NAMES[s]} ${cards}: you check, ${vName} bets ${bb(b)}, you call.`);
    pot+=2*b;stack-=b;
  }
  const bet=Math.min(stack,round(pot*pick(SIZES)));
  const last=board.slice(street?2+street:0).join(' ');
  story.push(ip?`${STREET_NAMES[street]} ${last}: the big blind bets ${bb(bet)} into ${bb(pot)}.`:`${STREET_NAMES[street]} ${last}: you check, ${vName} bets ${bb(bet)} into ${bb(pot)}.`);
  const raiseTo=Math.min(stack,round(Math.max(3*bet,bet+pot*.6)));
  return {hero,board,street:STREET_NAMES[street],pot,bet,stack,raiseTo,position:ip?'IP':'OOP',villain:vName,story};
}

function grade(s){
  const state={pot:s.pot+s.bet,currentBet:s.bet,minRaise:s.bet,bb:BB,board:s.board,hand:1,street:s.street,
    players:[{hole:s.hero,bet:0,stack:s.stack,folded:false,allin:false,line:s.position==='IP'?2:1},
             {hole:['?','?'],bet:s.bet,stack:s.stack-s.bet,folded:false,allin:s.stack===s.bet,line:2}]};
  const A=R.analyze(state,0,ITERS),all=s.raiseTo>=s.stack;
  const opts={fold:R.grade(A,'fold',0),call:R.grade(A,'call',0)};
  if(A.canRaise)opts.raise=R.grade(A,'raise',s.raiseTo);
  const out={};
  for(const [k,g] of Object.entries(opts))out[k]={label:g.label,glyph:g.glyph,lossBB:+g.lossBB.toFixed(1)};
  return {grades:out,eq:+A.eq.toFixed(3),need:+(A.toCall/(A.pot+A.toCall)).toFixed(3),raiseLabel:A.canRaise?(all?`All-in ${bb(s.stack)}`:`Raise to ${bb(s.raiseTo)}`):null};
}

// A spot is a good puzzle when exactly one answer grades well and the others are clear errors.
function clearAnswer(grades){
  const keys=Object.keys(grades),good=keys.filter(k=>GOOD.has(grades[k].label));
  if(good.length!==1||keys.length<3)return null;
  return keys.every(k=>k===good[0]||CLEAR.has(grades[k].label))?good[0]:null;
}

const puzzles=[];
const rand=R.mulberry32(20261020);
const want=['call','fold','raise'];
for(let d=0;d<DAYS;d++){
  // Rotate the target answer so the right move isn't always the same; settle for any clear spot if one is rare.
  let made=null;
  for(let attempt=0;!made&&attempt<4000;attempt++){
    const s=spot(rand);if(!s)continue;
    const g=grade(s),best=clearAnswer(g.grades);
    if(!best||(attempt<1500&&best!==want[d%3]))continue;
    made={n:d+1,...s,raiseLabel:g.raiseLabel,callLabel:`Call ${bb(s.bet)}`,eq:g.eq,need:g.need,best,grades:g.grades};
  }
  if(!made)throw Error('No clear spot found for day '+(d+1));
  puzzles.push(made);
  if((d+1)%30===0)console.log('built',d+1);
}
const counts=puzzles.reduce((m,p)=>(m[p.best]=(m[p.best]||0)+1,m),{});
writeFileSync(new URL('../worker/puzzles.js',import.meta.url),
`/* Generated by scripts/make-puzzles.mjs — do not edit by hand. One daily puzzle per day from ${START}.
   Answers: ${JSON.stringify(counts)}. */
export const PUZZLE_START='${START}';
export const PUZZLES=${JSON.stringify(puzzles)};
`);
console.log('Wrote',puzzles.length,'puzzles',counts);
