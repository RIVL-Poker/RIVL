// Builds clip-spots.js: 20 graded decisions for the recordable clip playthrough (clip-mode.js, open the site with
// ?clips). They are made the same way as the daily puzzles (scripts/make-puzzles.mjs) but from their own seed, so
// they never give away a daily puzzle's answer. Clips want a clear answer people can argue about in 20 seconds, so
// only Easy and Medium spots are kept, the answer rotates fold, call, raise, and the streets are mostly flops.
// Run: node scripts/make-clips.mjs   (deterministic: the same input always builds the same file)
import {writeFileSync} from 'node:fs';
import {spot,grade,clearAnswer,difficultyOf,build} from './make-puzzles.mjs';
const R=globalThis.RivlRating;
const COUNT=20,QUICK=1500;
// Street of each clip, in order: 8 flops, 6 turns, 6 rivers, mixed so the playthrough doesn't repeat itself.
const STREETS=['Flop','Turn','Flop','River','Flop','Turn','River','Flop','Turn','Flop','River','Flop','Turn','River','Flop','Turn','River','Flop','Turn','River'];
const WANT=['call','fold','raise'];
const rand=R.mulberry32(20261107);
const clips=[],seen=new Set();
for(let i=0;i<COUNT;i++){
  let made=null;
  for(let attempt=0;!made&&attempt<20000;attempt++){
    const s=spot(rand);if(!s||s.street!==STREETS[i])continue;
    const key=s.hero.join()+s.board.join();if(seen.has(key))continue;
    const ok=r=>{const best=clearAnswer(r.grades);if(!best||best==='fold'&&r.eq<.1||r.eq>.92)return null;
      const d=difficultyOf(r.grades,best);if(d!=='Easy'&&d!=='Medium'||attempt<15000&&best!==WANT[i%3])return null;return {best,d}};
    if(!ok(grade(s,QUICK)))continue;
    const r=grade(s),k=ok(r);if(!k)continue;
    seen.add(key);made=build(s,k.best,r,k.d,i+1);
  }
  if(!made)throw Error('No clip found for #'+(i+1));
  clips.push(made);console.log('clip',i+1,made.street,made.best,made.difficulty);
}
writeFileSync(new URL('../clip-spots.js',import.meta.url),
`/* Generated by scripts/make-clips.mjs — do not edit by hand. The 20 spots of the clip playthrough (clip-mode.js). */
window.RIVL_CLIPS=${JSON.stringify(clips)};
`);
